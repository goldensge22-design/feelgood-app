import { assert, base, context, enter, goto, workspace, check, finish } from './nuvia-browser-utils.mjs';
const c = await context(360);
const p = await c.newPage();
await check('server-committed-response-lost-refresh-retry-no-duplicate', async () => {
  await enter(p, 'teen', '/planner?lang=en');
  if (await p.getByTestId('form-plan').count()) await p.getByTestId('button-plan-cancel').click();
  await p.getByTestId('button-new-plan').click();
  const title = `가상 응답 유실 검증 ${Date.now()}`;
  await p.getByTestId('input-plan-title').fill(title);
  await p.getByTestId('input-plan-steps').fill('Fictional retained step');
  let intercepted = false;
  const handler = async route => {
    if (route.request().method() !== 'POST' || intercepted) return route.continue();
    intercepted = true;
    const response = await route.fetch();
    assert.equal(response.status(), 200);
    await route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"simulated_failure"}' });
  };
  await p.route('**/api/nuvia/subjects/demo-teen', handler);
  await p.getByTestId('button-plan-save').click();
  await p.getByTestId('form-plan').getByTestId('status-error').waitFor();
  assert.equal(await p.getByTestId('input-plan-title').inputValue(), title);
  assert.equal((await workspace(p, 'demo-teen')).plans.filter(x => x.title === title).length, 1);
  await p.reload();
  await p.getByTestId('input-plan-title').waitFor();
  assert.equal(await p.getByTestId('input-plan-title').inputValue(), title);
  await p.unroute('**/api/nuvia/subjects/demo-teen', handler);
  await p.getByTestId('button-plan-save').click();
  await p.getByTestId('form-plan').waitFor({ state: 'detached' });
  assert.equal((await workspace(p, 'demo-teen')).plans.filter(x => x.title === title).length, 1);
});
await check('browser-conflict-retains-input-refreshes-version-retry', async () => {
  await p.getByTestId('button-new-plan').click();
  const title = `가상 충돌 검증 ${Date.now()}`;
  await p.getByTestId('input-plan-title').fill(title);
  await p.getByTestId('input-plan-steps').fill('Fictional conflict recovery step');
  const ws = await workspace(p, 'demo-teen');
  const r = await p.request.post(`${base}/api/nuvia/subjects/demo-teen`, { data: { type: 'saveNote', text: '가상 동시 수정 검증 메모', version: ws.version, requestId: crypto.randomUUID() } });
  assert.equal(r.status(), 200);
  await p.getByTestId('button-plan-save').click();
  await p.getByTestId('form-plan').getByTestId('status-error').waitFor();
  assert.equal(await p.getByTestId('input-plan-title').inputValue(), title);
  assert.equal((await workspace(p, 'demo-teen')).plans.filter(x => x.title === title).length, 0);
  await p.getByTestId('button-plan-save').click();
  await p.getByTestId('form-plan').waitFor({ state: 'detached' });
  assert.equal((await workspace(p, 'demo-teen')).plans.filter(x => x.title === title).length, 1);
});
await check('browser-story-stale-source-blocked-reconfirm-save', async () => {
  const ws = await workspace(p, 'demo-teen');
  const r = await p.request.post(`${base}/api/nuvia/subjects/demo-teen`, { data: { type: 'history', title: `가상 원본 재확인 ${Date.now()}`, action: 'Fictional action to reconfirm', outcome: 'tried', version: ws.version, requestId: crypto.randomUUID() } });
  assert.equal(r.status(), 200);
  const rec = (await r.json()).records.at(-1);
  await goto(p, '/story?lang=en');
  for (const box of await p.locator('input[data-testid^="checkbox-record-"]').all()) await box.uncheck();
  await p.getByTestId(`checkbox-record-${rec.id}`).check();
  await p.getByTestId('button-story-prefill').click();
  const share = p.getByTestId(`toggle-share-${rec.id}`);
  await share.click();
  await p.waitForFunction(id => document.querySelector(`[data-testid="toggle-share-${id}"]`)?.checked, rec.id);
  await p.getByTestId('button-story-preview').click();
  await p.getByTestId('button-story-save').click();
  await p.getByTestId('form-story').getByTestId('status-error').waitFor();
  assert.ok((await p.getByTestId('form-story').getByTestId('status-error').innerText()).includes('changed'));
  assert.ok((await p.getByTestId('input-story-text').inputValue()).includes('Fictional action'));
  await p.getByTestId('button-story-prefill').click();
  await p.getByTestId('button-story-preview').click();
  await p.getByTestId('button-story-save').click();
  await p.getByTestId('input-story-text').waitFor({ state: 'detached' });
  assert.ok((await workspace(p, 'demo-teen')).drafts.some(d => d.recordIds.includes(rec.id)));
});
await finish('edge');
