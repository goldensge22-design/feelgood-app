export const t=(l:Locale,k:CopyKey)=>COPY[l][k];

/** Canonical synthetic fixture. Stored strings are English; display localizes only an exact match. */
const JOBS=['Project planning','Data analysis','Design','Research','Operations'];
const FIXTURE_INTERP='Synthetic example value. No interpretation.';
export function getFixtureReport():Report{
 const scores=[42,58,76,65],levels=['L','M','H','M'];
 return {schema:'nuvia-career-review-report/v1',id:'review-fixture-adult',version:'1',population:'adult',
  source:{name:'Fictional review source',issuedAt:'2025-01-01',uri:''},synthetic:true,
  pass:(['planning','attention','simultaneous','successive'] as const).map((id,i)=>({id,score:scores[i],unit:'%',level:levels[i],interpretation:FIXTURE_INTERP})),
  occupations:JOBS.map((label,i)=>({id:`fixture-job-${i+1}`,rank:i+1,label:`${label} (fictional)`,source:'review-fixture'}))};
}
const FIXTURE_BYTES=JSON.stringify(getFixtureReport());
export const isFixture=(r:Report|undefined|null)=>!!r&&JSON.stringify(r)===FIXTURE_BYTES;
/** Display helper: localizes only the exact canonical fixture; anything else is shown raw. */
export function display(l:Locale,r:Report){
 const fx=isFixture(r);
 return {fixture:fx,source:fx?t(l,'fixtureSource'):r.source.name,
  interp:(i:number)=>fx?t(l,'fixtureInterp'):r.pass[i].interpretation,
  job:(i:number)=>fx?t(l,`job${i+1}` as CopyKey):r.occupations[i].label};
}
/** Localize a stored choice label only when it is an unchanged fixture occupation. */
export function choiceLabel(l:Locale,report:Report|undefined,choice:{kind:string;id:string;label:string}){
 if(choice.kind==='recommended'&&isFixture(report)){const i=report!.occupations.findIndex(o=>o.id===choice.id&&o.label===choice.label);if(i>=0)return t(l,`job${i+1}` as CopyKey);}
 return choice.label;
}
