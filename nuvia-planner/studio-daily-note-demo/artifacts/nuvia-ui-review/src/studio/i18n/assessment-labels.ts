import {currentLocale,label} from './runtime';
import {demoText} from './demo-resources';

// Display-only enum mapping. Never translate free-form assessment names or data.
export const levelLabel=(level:string)=>String(label(({low:'하',mid:'중',high:'상'} as Record<string,string>)[level]??level));
export const metricLabel=(metric:string|undefined)=>String(label(({standard_score:'표준점수',accuracy_rate:'정답률',percentile:'백분위'} as Record<string,string>)[metric??'']??metric??''));
export const responseLabel=(answer:string|undefined)=>String(label(({yes:'도움 됨',neutral:'중립',no:'도움되지 않음',unsure:'모르겠어요',agree:'맞아요',different:'달라요'} as Record<string,string>)[answer??'']??answer??'미응답'));
export const draftStatusLabel=(status:string)=>String(label(({pending:'검토 중',accepted:'받아들임',deferred:'미룸'} as Record<string,string>)[status]??status));

// These exact labels are generated by our isolated demo, not original results.
// All other kinds, IDs, score-system names and user text are returned verbatim.
export function assessmentLabel(value:string|undefined,sourceId:string|undefined){
 if(!sourceId?.startsWith('external-dcas-synthetic-'))return value;
 for(const [original,key] of [['D-CAS 청소년용 합성 예시','youth'],['D-CAS 성인용 합성 예시','adult']] as const){
  if(value===original)return demoText(key);
  if(value===original+' · 영역별 정답률')return demoText(key)+' · '+String(label('정답률'));
 }
 return value;
}
