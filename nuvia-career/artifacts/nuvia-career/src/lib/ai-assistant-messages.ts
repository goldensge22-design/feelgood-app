import { capacityMessage } from './ai-capacity-messages';

export function aiTranslator(
  locale: string,
  base: (key: string, vars?: Record<string, string | number>) => string,
) {
  return (key: string, vars?: Record<string, string | number>) => {
    const capacity = capacityMessage(locale, key);
    if (capacity) return capacity;
    if (key.startsWith('ai.sourceValue.')) return base(`expsrc.${key.slice('ai.sourceValue.'.length)}`, vars);
    if (key.startsWith('ai.cardValue.')) return base(`pv.ct.${key.slice('ai.cardValue.'.length)}`, vars);
    if (key.startsWith('ai.contextValue.')) {
      const suffix = key.slice('ai.contextValue.'.length);
      const contexts: Record<string, string> = { daily_activity: 'daily', class_simulation: 'classSimulation', job_experience: 'jobExperience', synthetic_example: 'synthetic', unknown: 'unknown' };
      return base(`joblink.context.${contexts[suffix] || 'unknown'}`, vars);
    }
    const extraIndex = ['ai.localNotice', 'ai.history', 'ai.provenanceNotice'].indexOf(key);
    const analyzeIndex = ['ai.analyze', 'ai.analyzeHelp'].indexOf(key);
    const message = key === 'ai.connectionRequired' ? AI_CONNECTION[locale]
      : key === 'ai.stale' ? AI_STALE[locale]
      : key === 'ai.factsReview' ? AI_FACTS[locale]
      : key === 'ai.recommendationBasis' ? AI_SUPPORT[locale]
      : analyzeIndex >= 0 ? AI_ANALYZE[locale]?.[analyzeIndex]
      : extraIndex >= 0 ? AI_LOCAL[locale]?.[extraIndex] : AI_MESSAGES[locale]?.[key];
    const alias = AI_ALIASES[key];
    let value = message ?? (alias ? base(alias, vars) : key);
    if (message && vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.split(`{${name}}`).join(String(replacement));
      }
    }
    return value;
  };
}
