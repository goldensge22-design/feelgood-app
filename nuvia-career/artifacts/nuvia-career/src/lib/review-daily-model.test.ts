import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createDailyDraft,dailyContext,validDailyDate } from './review-daily-model';
import { reviewHomeFixture } from './review-home-profile';
import { registerDailyCard,isReviewBook,newReviewBook,registerEverydayCard,applyCardNote,approveCardRevision,reviewCardExperience } from './review-planner-model';
import { generateEverydayPlans, initialChoice, contextOf, matchOf } from './review-everyday-model';
import { DAILY_MESSAGES } from './review-daily-messages';
import { approvedPublicPartnerPostings,matchingPartnerPosting,partnerPostingStatus,partnerWatchlist } from './review-partner-postings';
const t=(key:string,vars:Record<string,string|number>={})=>(DAILY_MESSAGES[key]?.[0] ?? key).replace(/\{(\w+)\}/g,(_,k)=>String(vars[k]??''));
const id1='review-card-0f632ba8-af38-4f08-8a53-42154977df45';
const id2='review-card-b62dd6e9-c0da-413d-8104-a2a1c3eb5481';
test('report source and focus are independent and recommendation never reads scores',()=>{
  const fixture=reviewHomeFixture('planning','simultaneous');
  const context=dailyContext(fixture,'demo-education','planning','simultaneous',true);
  assert.equal(context.job?.id,'demo-education');
  assert.match(context.job?.source ?? '',/가상 결과지/);
  assert.equal(context.trait,'planning');
  assert.equal(context.focus,'simultaneous');
  const noFocus=dailyContext({...fixture,growthPoints:[]},'','planning','simultaneous',true);
  assert.equal(noFocus.focus,undefined);
  assert.equal(noFocus.job?.id,fixture.topJobs?.[0].id);
  const generic=dailyContext(null,'demo-education','attention','sequential',true);
  assert.deepEqual([generic.synthetic,generic.job,generic.trait,generic.focus],[false,null,undefined,undefined]);
  assert.match(createDailyDraft(id1,'2026-11-20','cognitive',generic,0,t).activity.linkReason,/자료가 없어/);
});
test('daily card is idempotent; an older card and its version keep their original note',()=>{
  const ctx=contextOf(initialChoice)!;
  const activity=generateEverydayPlans(ctx.need,ctx.trait,ctx.focus)[0];
  const date='2026-11-20';
  const old=registerEverydayCard(newReviewBook(),id1,{match:matchOf(initialChoice)!,activity,worksheet:{date,before:'기존 생각',observation:'',reflection:''}})!;
  const note={action:'예전 기록',result:'',learning:'',next:''};
  const used=applyCardNote({...old,noteEdits:{[id1]:note}},id1)!;
  const confirmed=approveCardRevision(used,id1,used.cards[id1].revision)!;
  const draft=createDailyDraft(id2,date,'cognitive',dailyContext(null,'',undefined,undefined),0,t);
  const added=registerDailyCard(confirmed,id2,draft)!;
  assert(isReviewBook(added));
  assert.equal(added.cards[id2].note,null);
  assert.equal(added.cards[id2].status,'planned');
  assert.equal(added.cards[id1],confirmed.cards[id1]);
  assert.equal(reviewCardExperience(added.cards[id1])?.action,note.action);
  assert.equal(registerDailyCard(added,id2,draft),added);
  assert.equal(registerDailyCard(added,id2,{...draft,worksheet:{...draft.worksheet,before:'다른 생각'}}),null);
  assert(!validDailyDate('2026-02-29'));
});
test('three approved sources attach only to the correct recruiter; Korea closing date is inclusive',()=>{
  assert.equal(partnerWatchlist.length,8);
  assert.equal(partnerWatchlist.filter(x=>x.recruiter==='바스').length,1);
  assert.equal(partnerWatchlist.filter(x=>x.recruiter==='프로에스콤').length,7);
  assert.equal(approvedPublicPartnerPostings.length,3);
  const posting=approvedPublicPartnerPostings[0];
  const site=partnerWatchlist.find(s=>s.id===posting.siteId)!;
  assert(matchingPartnerPosting(site,posting));
  assert(!matchingPartnerPosting(site,{...posting,employer:'다른 진행회사'}));
  assert.equal(partnerPostingStatus(posting,'2026-09-22'),'pending');
  assert.equal(partnerPostingStatus(posting,'2026-11-22'),'open');
  assert.equal(partnerPostingStatus(posting,'2026-11-23'),'closed');
  assert.equal(partnerPostingStatus(undefined,'2026-11-20'),'pending');
});
