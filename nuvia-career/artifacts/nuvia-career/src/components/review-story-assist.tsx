import { useState } from 'react';
import { Link } from 'wouter';
import { BookOpenText, RotateCcw } from 'lucide-react';
import { cardActivity, type ReviewCard } from '@/lib/review-planner-model';
import type { StoryboardDraft, StorySections } from '@/lib/storyboard';
import { buildGroundedSections, contextOf, emptyStoryThoughts } from '@/lib/review-everyday-model';
import { retryEveryday, saveEverydayOriginal, saveEverydayPreview, saveStoryThoughts, useEveryday } from '@/lib/review-everyday-store';
import { DAILY_EVIDENCE } from '@/lib/review-daily-model';
import { useI18n } from '@/lib/i18n';
import { labReportVersion } from '@/lib/review-lab-analysis';

const primary = 'inline-flex min-h-11 items-center justify-center gap-2 rounded-xl bg-primary px-4 text-sm font-semibold text-primary-foreground disabled:opacity-45';
const secondary = 'inline-flex min-h-11 items-center justify-center gap-2 rounded-xl border bg-card px-4 text-sm font-semibold disabled:opacity-45';
const sceneNames = ['나를 소개하는 한 문장','관심 기업·직무와 이유','내가 판단하고 행동한 경험','배운 점과 다음 적용'];
export function ReviewStoryAssist({draft,cards,ready,apply}: {draft:StoryboardDraft;cards:(ReviewCard|undefined)[];ready:boolean;apply:(sections:StorySections)=>void}) {
  const {value,error}=useEveryday();
  const {t}=useI18n();
  const current=contextOf(value.choice)!;
  const preview=value.previews[draft.id];
  const refined=value.refinements?.[draft.id];
  // A rollback snapshot can be older (even blank) after edits or evidence
  // re-confirmation. It must never replace the editor in the comparison.
  const rollback=value.originals[draft.id];
  const thoughts=value.thoughts?.[draft.id] ?? emptyStoryThoughts;
  const [message,setMessage]=useState('');
  const notes=cards.flatMap(c=>c?.note?[{...c.note,thought:cardActivity(c)?.activity.kind==='thought',dailyNote:cardActivity(c)?.activity.entry==='daily_note',direct:c.kind==='free'}]:[]);
  const independent=draft.evidenceKey===DAILY_EVIDENCE;
  const matched=!independent && value.version===value.confirmedVersion;
  const valid=ready && notes.length>0 && notes.length===cards.length && !!draft.evidenceKey;
  const labOutdated=!!draft.reviewInterest?.lab&&draft.reviewInterest.lab.reportVersion!==labReportVersion(current.trait.id,current.focus?.id??null);
  const stamp=JSON.stringify(independent || draft.reviewInterest ?
    [draft.sourceRevision,draft.evidenceSources,draft.company,draft.job,draft.reviewInterest,labOutdated] : [draft.sourceRevision,draft.evidenceSources]);
  const hasReviewThought=!!(thoughts.feeling.trim() || thoughts.keyPoint.trim());
  // Invalidate older demo previews that appended expression guidance as prose.
  const refinedStamp=JSON.stringify(['review-refine-v2',stamp,thoughts.feeling,thoughts.keyPoint]);
  const currentPreview=!!preview && valid && preview.evidence===draft.evidenceKey && preview.source===stamp;
  const currentRefined=!!refined && valid && refined.evidence===draft.evidenceKey && refined.source===refinedStamp;
  function generate(refine=false) {
    if (!valid || !draft.evidenceKey || (refine && !hasReviewThought)) return;
    const sections=buildGroundedSections(matched?current.role:null,matched?current.need:null,...notes);
    if(!matched){
      sections[0]=t('daily.storyLead');
      sections[1]=draft.reviewInterest&&!labOutdated ? t('daily.storyInterest',{interest:[draft.company,draft.job].filter(Boolean).join(' · ')}) : '';
    }
    // Keep self-reported thoughts distinct from action/result facts. This is
    // a local comparison aid, not text generated by a model.
    if (refine) {
      if (thoughts.keyPoint.trim()) sections[0]=thoughts.keyPoint;
      if (thoughts.feeling.trim()) sections[3]=[sections[3],thoughts.feeling].filter(Boolean).join('\n\n');
    }
    const ok=saveEverydayPreview(draft.id,{evidence:draft.evidenceKey,source:refine?refinedStamp:stamp,sections},refine);
    setMessage(ok ? '후보를 준비했습니다. 아직 본문은 바뀌지 않았습니다.' : '후보를 저장하지 못했습니다. 본문은 바뀌지 않았습니다.');
    if(ok)requestAnimationFrame(()=>document.getElementById('review-story-compare')?.focus());
  }
  function accept(refine:boolean) {
    const choice=refine?refined:preview;
    if (!(refine?currentRefined:currentPreview) || !choice || error) return;
    if(!saveEverydayOriginal(draft.id,draft.sections)) {setMessage('적용 전 글을 저장하지 못했습니다. 본문은 바뀌지 않았습니다.');return;}
    apply(choice.sections);
    setMessage('후보를 편집기에 넣었습니다. 필요하면 수정하거나 적용 전 글로 되돌릴 수 있습니다.');
    requestAnimationFrame(()=>document.getElementById('storyboard-write')?.focus());
  }
  return <section aria-labelledby="review-story-candidate" className="space-y-4 rounded-2xl border border-primary/30 bg-card p-4 sm:p-6" lang="ko">
    <h2 id="review-story-candidate" className="font-display text-xl font-bold">나의 강점 스토리보드 초안</h2>
    <p className="text-sm leading-relaxed">내가 확인한 일상기록으로 정리합니다. 기업·직무 자료는 선택입니다. <strong>규칙 기반 초안</strong>이며 실시간 AI가 아닙니다. 가상 직무의 실제 근무나 확인된 성과로 바꾸지 않습니다.</p>
    <div className="grid gap-3 rounded-xl bg-blue-soft p-3 text-sm md:grid-cols-3" data-testid="view-review-story-evidence">
      <div><p className="font-bold">결과지 요약</p><p>강점과 지원: {current.trait.title} · {current.trait.summary}</p><p className="mt-1">보완 필요영역: {current.focus ? `${current.focus.title} · ${current.focus.summary}` : '자료 없음 · 연결 필요'}</p><p className="mt-1 text-xs">가상 프로필 · 검사 수치는 작성 자료에 넣지 않아요.</p></div>
      <div><p className="font-bold">{t('daily.lab.summary')}</p>{draft.reviewInterest?<div data-testid="text-review-story-interest">
        <p>{[draft.company,draft.job].filter(Boolean).join(' · ')}</p><p className="break-all text-xs">{draft.reviewInterest.source||t('daily.lab.none')}</p>
        <p className="text-xs">{t(draft.reviewInterest.lab?.mode==='gpt-web'?'daily.lab.gptSource':
          draft.reviewInterest.lab?.mode==='curated'?'daily.lab.curatedSource':draft.reviewInterest.synthetic?'daily.lab.sample':'daily.lab.user')}</p>
        {draft.reviewInterest.lab&&<details className="text-xs" data-testid="view-story-lab-connection">
          <summary className="min-h-11 cursor-pointer content-center font-semibold">{draft.reviewInterest.lab.representative.keyword} · {draft.reviewInterest.lab.strength}</summary>
          <p>“{draft.reviewInterest.lab.representative.excerpt}”</p>
          <p>{draft.reviewInterest.lab.representative.source} · {draft.reviewInterest.lab.retrievedAt.slice(0,10)}</p>
          <p>{draft.reviewInterest.lab.support} {draft.reviewInterest.lab.check} {draft.reviewInterest.lab.planner}</p>
          <p>가상 결과지와 연결한 자료이며 본문에 자동으로 넣지 않아요.</p>
          {labOutdated&&<p>결과지 기준이 바뀌었어요. <Link href="/lab" className="text-blue underline">LAB에서 강점 연결 다시 확인</Link></p>}
        </details>}
      </div>:matched?<><p>직무 필요역량: {current.need.title}</p><p>{current.role.sourceTitle} ({current.role.sourceVersion})</p><p>“{current.need.quote}”</p><p className="mt-1">{current.need.reason} {current.trait.support}</p></>:<p>{t('daily.lab.unset')}</p>}</div>
      <div><p className="font-bold">확인한 일상기록 {valid ? notes.length : 0}개</p>
        {valid && <p className="py-1 text-xs font-semibold text-ok" role="status" data-testid="status-review-story-sources-saved">스토리보드 작성 자료에 저장됨 · 이 탭</p>}
        {valid && cards.map((card,i)=>{
          if(!card) return null;
          const origin=card.everyday;
          const provided=origin && contextOf(origin.match);
          return <details key={card.id} className="mt-1 border-t border-blue/15" data-testid={`review-story-source-${card.id}`}>
            <summary className="min-h-11 cursor-pointer content-center font-semibold">{card.plan.goal}</summary>
            <p className="whitespace-pre-wrap break-words text-sm">{notes[i].dailyNote?'내가 적은 일상 기록: ':notes[i].thought?'가정 상황 생각 연습: ':''}{notes[i].action}</p>
            <p className="mt-1 break-words text-xs">{origin?.worksheet.date ?? card.plan.when} · 플래너 기록 v{card.revision}</p>
            {origin && provided && <p className="mt-1 break-words text-xs">{provided.role.company} · {provided.role.job} · {provided.need.title} · {origin.match.reportVersion} · {provided.role.sourceTitle} / {origin.match.roleVersion}</p>}
            {card.daily && <p className="mt-1 break-words text-xs">{t(`daily.${card.daily.category}`)} · {card.daily.activity.linkReason}</p>}
            <p className="mt-1 break-words text-xs">{card.kind==='free'?'출처: 직접 일상 기록':'출처: 플래너 일상기록'}</p>
            <Link href={`/planner/card/${card.id}`} className="inline-flex min-h-11 items-center text-sm font-semibold text-blue underline" data-testid={`link-review-story-source-${card.id}`}>플래너 원본 열기</Link>
          </details>;
        })}
        <p className="mt-1 text-xs">생각 연습과 실제 적용은 별도 · 직무능력의 증명이 아님</p></div>
    </div>
    {!valid && <p role="note" className="text-sm" data-testid="notice-review-story-recheck">플래너에서 기록을 저장하고 작성에 사용할 원본을 확인해 주세요. 이미 쓴 문장과 확정 버전은 그대로 남습니다. <Link href="/planner" className="inline-flex min-h-11 items-center font-semibold text-blue underline">플래너 일상기록 열기</Link></p>}
    <button type="button" className={primary} disabled={!valid || !!error} onClick={()=>generate()} data-testid="button-review-build-story"><BookOpenText className="h-4 w-4" />내 기록으로 강점 스토리보드 만들기</button>
    <fieldset className="space-y-2 rounded-xl border p-3">
      <legend className="font-bold">나의 생각으로 문장 다듬기</legend>
      <p className="text-sm text-muted-foreground">체험에서는 직접 입력한 말을 정리한 별도 규칙형 후보를 보여줍니다. 결과나 경력을 만들어 넣지 않습니다.</p>
      <div className="grid gap-2 md:grid-cols-3">{([['feeling','느낀 점'],['keyPoint','말하고 싶은 핵심'],['expression','선호 표현']] as const).map(([k,label])=>
        <label key={k} className="block min-w-0 text-sm font-semibold">{label}{k==='expression' && <span id="review-expression-help" className="mt-1 block text-xs font-normal text-muted-foreground">여기에는 메모로 보관돼요. 데모 후보에는 들어가지 않으며 말투 반영은 실제 AI에서만 지원합니다.</span>}<textarea className="mt-1 block min-h-11 w-full rounded-lg border bg-card p-2 font-normal" rows={2}
          placeholder={k==='expression'?'예: 짧고 담백하게':undefined} aria-describedby={k==='expression'?'review-expression-help':undefined}
          maxLength={500} dir="auto" value={thoughts[k]} onChange={e=>saveStoryThoughts(draft.id,{[k]:e.target.value})} data-testid={`input-review-thought-${k}`}/></label>)}</div>
      <button className={secondary} type="button" disabled={!valid || !!error || !hasReviewThought} onClick={()=>generate(true)}
        data-testid="button-review-build-refined">내 생각을 반영한 규칙형 후보 만들기</button>
    </fieldset>
    <aside className="space-y-2 rounded-xl border p-3">
      <p className="text-sm"><strong>실제 AI 이용:</strong> 검토용 데모는 미연결이며 실제 AI를 호출하지 않습니다. 로그인한 기존 작업 공간에서 내 계정의 확인된 자료와 AI 전송 동의를 사용하세요. 이 탭의 기록은 자동으로 옮기지 않습니다.</p>
      <button type="button" className={secondary} disabled data-testid="button-review-real-ai">AI 문장 만들기 · 로그인 필요</button>
      <button type="button" className={secondary} disabled data-testid="button-review-real-refine">AI로 생각 반영하여 다듬기 · 로그인 필요</button>
      <a className="inline-flex min-h-11 items-center text-sm font-semibold text-blue underline" href={`${import.meta.env.BASE_URL.replace(/\/$/,'')}/storyboard`}>로그인 가능한 작업 공간 열기</a>
    </aside>
    {error && <p role="alert" className="text-sm text-destructive">이 탭에 임시 내용을 보관하지 못했습니다. <button type="button" className="min-h-11 underline" onClick={retryEveryday}>다시 시도</button></p>}
    {(preview || refined) && <div id="review-story-compare" tabIndex={-1} data-testid="view-review-story-preview" className="scroll-mt-4 space-y-3 rounded-xl border bg-muted/30 p-4">
      <h3 className="font-display font-bold">적용 전 미리 보기</h3>
      {(preview && !currentPreview || refined && !currentRefined) && <p role="alert" className="text-sm text-destructive">자료나 후보 만들기 규칙이 바뀌면 예전 후보는 적용할 수 없어요. 다시 만들어 주세요.</p>}
      <div className="grid gap-2 md:grid-cols-3">
        {([{label:'내 원문',sections:draft.sections,key:'original'}, {label:'규칙 기반 제안 (AI 미사용)',sections:preview?.sections,key:'preview'}, {label:'나의 생각 반영안 (AI 미사용)',sections:refined?.sections,key:'refined'}]).map(column=><div key={column.key} className="min-w-0 space-y-2 rounded-lg bg-card p-3">
          <h4 className="text-sm font-bold text-blue">{column.label}</h4>
          {column.sections ? column.sections.map((section,index)=><div key={index}><p className="text-xs font-bold">{sceneNames[index]}</p><p className="whitespace-pre-wrap break-words text-sm"
            data-testid={`text-review-story-${column.key}-${index+1}`}>{section || '미작성'}</p></div>) : <p className="text-sm text-muted-foreground">아직 만들지 않았습니다.</p>}
        </div>)}
      </div>
      <div className="flex flex-wrap gap-2">
        <button type="button" className={primary} disabled={!currentPreview || !!error || draft.sections.every((s,i)=>s===preview?.sections[i])} onClick={()=>accept(false)} data-testid="button-review-apply-story">규칙형 초안을 편집기에 적용</button>
        <button type="button" className={secondary} disabled={!currentRefined || !!error || draft.sections.every((s,i)=>s===refined?.sections[i])} onClick={()=>accept(true)} data-testid="button-review-apply-refined">나의 생각 반영안을 편집기에 적용</button>
      </div>
    </div>}
    {rollback && <button type="button" className={secondary} disabled={draft.sections.every((s,i)=>s===rollback[i])}
      onClick={()=>{apply(rollback);setMessage('마지막으로 후보를 적용하기 직전의 글을 복원했습니다.');}} data-testid="button-review-restore-writing"><RotateCcw className="h-4 w-4" />적용 전 내 글 복원</button>}
    {message && <p role="status" className="text-sm text-muted-foreground">{message}</p>}
  </section>;
}
